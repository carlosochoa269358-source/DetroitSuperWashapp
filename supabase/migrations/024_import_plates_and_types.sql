INSERT INTO vehicles (company_id, customer_id, vehicle_type_id, plate)
SELECT c.company_id, c.id, vt.id, p.placa
FROM _placas_import p
JOIN customers c ON c.phone = p.telefono AND c.company_id = (SELECT id FROM companies LIMIT 1)
JOIN vehicle_types vt ON vt.name = p.tipo_nombre
ON CONFLICT (company_id, plate) DO NOTHING;

